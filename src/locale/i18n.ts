// App locale (P5): the 8 carried Keystone locales (v1
// `frontend/src/i18n` parity). Own-storage-key pref store following the
// `feedPrefs` pattern — device-local, validated parse, `'en'` fallback,
// subscriber notify. The catalog for every locale is statically imported
// (small: UI chrome only) so switching is synchronous with no loader UI.
//
// Re-render: `Root` already wraps the tree in `I18nProvider` bound to this
// same `i18n` singleton, and `I18nProvider` re-renders on `activate` — so
// no coordinator touch is needed in `Root.tsx` for switching to work.

export const SUPPORTED_LOCALES = [
  {code: 'en', nativeName: 'English'},
  {code: 'fr', nativeName: 'Français'},
  {code: 'de', nativeName: 'Deutsch'},
  {code: 'zh-CN', nativeName: '简体中文'},
  {code: 'zh-TW', nativeName: '繁體中文'},
  {code: 'yue-HK', nativeName: '廣東話'},
  {code: 'ja', nativeName: '日本語'},
  {code: 'hi', nativeName: 'हिन्दी'},
] as const

export type LocaleCode = (typeof SUPPORTED_LOCALES)[number]['code']

export function isLocaleCode(code: unknown): code is LocaleCode {
  return SUPPORTED_LOCALES.some(l => l.code === code)
}

const CATALOGS: Record<LocaleCode, Messages> = {
  en: messagesEn,
  fr: messagesFr,
  de: messagesDe,
  'zh-CN': messagesZhCn,
  'zh-TW': messagesZhTw,
  'yue-HK': messagesYueHk,
  ja: messagesJa,
  hi: messagesHi,
}

export const LOCALE_STORAGE_KEY = 'keystone.locale'
export const DEFAULT_LOCALE: LocaleCode = 'en'

/** Validated parse of the stored locale: anything unknown is `'en'`. Pure. */
export function parseLocale(raw: string | null): LocaleCode {
  if (!raw) return DEFAULT_LOCALE
  let code: unknown = raw
  try {
    code = JSON.parse(raw)
  } catch {
    // Bare (unquoted) codes from older builds still parse as themselves.
  }
  if (typeof code !== 'string') return DEFAULT_LOCALE
  const trimmed = code.trim()
  return isLocaleCode(trimmed) ? trimmed : DEFAULT_LOCALE
}

export interface LocaleStore {
  get(): LocaleCode
  set(code: LocaleCode): void
  subscribe(fn: () => void): () => void
}

export function createLocaleStore(
  storage: () => KeyValueStore = appStorage,
): LocaleStore {
  const listeners = new Set<() => void>()
  const emit = () => {
    for (const listener of [...listeners]) listener()
  }
  const read = (): LocaleCode => {
    try {
      return parseLocale(storage().getItem(LOCALE_STORAGE_KEY))
    } catch {
      return DEFAULT_LOCALE
    }
  }
  // Cached by reference: `useSyncExternalStore` needs a stable snapshot.
  let cached: LocaleCode | null = null
  const get = (): LocaleCode => {
    if (!cached) cached = read()
    return cached
  }
  const load = (code: LocaleCode): void => {
    try {
      i18n.load(code, CATALOGS[code] ?? {})
      i18n.activate(code)
    } catch {
      // A broken catalog never blanks the UI: stay on the current locale.
    }
  }
  return {
    get,
    set(code: LocaleCode): void {
      if (!isLocaleCode(code) || code === get()) return
      cached = code
      try {
        storage().setItem(LOCALE_STORAGE_KEY, JSON.stringify(code))
      } catch {
        // Storage unavailable: the locale lasts for this session only.
      }
      load(code)
      emit()
    },
    subscribe(fn: () => void): () => void {
      listeners.add(fn)
      return () => {
        listeners.delete(fn)
      }
    },
  }
}

export const localeStore: LocaleStore = createLocaleStore()

// --- Dev-only pseudo-locale (X0.2 ratchet aid) -------------------------------
//
// `pseudo` renders every Lingui string accented and bracket-padded, so
// anything that still shows plain English under it is an untranslated
// literal. It is deliberately NOT in `SUPPORTED_LOCALES` and never reaches
// the production language picker. Reachable only in dev: `?locale=pseudo`
// on web, or the dev-only storage flag on native (a SysDebug-style toggle
// can call `setPseudoLocaleEnabled`). The catalog itself is generated by
// `pnpm intl:compile` (from `pseudoLocale: 'pseudo'` in `lingui.config.ts`);
// until then activation is a no-op that returns false.

export const PSEUDO_LOCALE = 'pseudo' as const

const PSEUDO_FLAG_KEY = 'keystone.dev.pseudoLocale'
const PSEUDO_CATALOG_SPECIFIER = './locales/pseudo/messages'

function isDevHost(): boolean {
  return (globalThis as {__DEV__?: unknown}).__DEV__ !== false
}

function webQueryRequestsPseudo(): boolean {
  try {
    const w = (globalThis as {window?: {location?: {search?: unknown}}}).window
    const search = w?.location?.search
    if (typeof search !== 'string' || !search) return false
    return new URLSearchParams(search).get('locale') === PSEUDO_LOCALE
  } catch {
    return false
  }
}

/** True only in a dev host: `?locale=pseudo` on web, or the dev-only
 * native flag. Never true in production. Pure (reads storage only). */
export function isPseudoLocaleEnabled(
  storage: () => KeyValueStore = appStorage,
): boolean {
  if (!isDevHost()) return false
  if (webQueryRequestsPseudo()) return true
  try {
    return storage().getItem(PSEUDO_FLAG_KEY) === JSON.stringify(true)
  } catch {
    return false
  }
}

/** Dev-only toggle for the native pseudo-locale flag. No-op in production. */
export function setPseudoLocaleEnabled(
  on: boolean,
  storage: () => KeyValueStore = appStorage,
): void {
  if (!isDevHost()) return
  try {
    if (on) storage().setItem(PSEUDO_FLAG_KEY, JSON.stringify(true))
    else storage().removeItem(PSEUDO_FLAG_KEY)
  } catch {
    // Storage unavailable: the flag lasts for this session only.
  }
}

/** Load and activate the generated pseudo catalog. Returns false (leaving
 * the current locale untouched) outside dev, or when the catalog has not
 * been generated yet. The specifier is a variable on purpose: the module
 * does not exist until `pnpm intl:compile` creates it, and a static import
 * would break typecheck before then. */
export async function activatePseudoLocale(): Promise<boolean> {
  if (!isDevHost()) return false
  try {
    const mod = (await import(PSEUDO_CATALOG_SPECIFIER)) as {
      messages?: Messages
    }
    if (!mod || !mod.messages) return false
    i18n.load(PSEUDO_LOCALE, mod.messages)
    i18n.activate(PSEUDO_LOCALE)
    return true
  } catch {
    return false
  }
}

// --- RTL readiness (X9.6) ---------------------------------------------------
//
// No RTL locale ships (all 8 carried locales are LTR), but layout uses
// logical `start`/`end` props throughout `src/` so a future RTL locale
// mirrors for free. These helpers are the seams it will use:

/** Primary language subtags written right-to-left (BCP-47, case-insensitive).
 * Checked against the tag's first subtag only, so `ar-EG` matches. Pure. */
const RTL_LANGS = new Set([
  'ar', // Arabic
  'he', // Hebrew
  'fa', // Persian
  'ur', // Urdu
  'ps', // Pashto
  'sd', // Sindhi
  'ug', // Uyghur
  'yi', // Yiddish
  'dv', // Dhivehi
  'ku', // Kurdish
  'ckb', // Central Kurdish
])

/** True when the BCP-47 tag's primary language is right-to-left. Pure. */
export function isRtlLocale(code: string): boolean {
  const primary = code.split('-')[0]?.toLowerCase() ?? ''
  return RTL_LANGS.has(primary)
}

// Dev-only RTL rehearsal: no RTL catalog ships, so the pseudo-locale gains
// an RTL mode instead. The flag persists in dev storage; the setter also
// nudges `I18nManager` (best-effort) so logical props mirror after the
// reload the OS layout direction requires. Directional icons read
// `isRtlNow()` at render and flip without a reload. Never true in
// production. No RTL locale is shipped.
const PSEUDO_RTL_FLAG_KEY = 'keystone.dev.pseudoRtl'

/** True only in a dev host with the RTL rehearsal flag set. Pure. */
export function isPseudoRtlEnabled(
  storage: () => KeyValueStore = appStorage,
): boolean {
  if (!isDevHost()) return false
  try {
    return storage().getItem(PSEUDO_RTL_FLAG_KEY) === JSON.stringify(true)
  } catch {
    return false
  }
}

/** Dev-only toggle for the RTL rehearsal flag. No-op in production. Takes
 * full effect after a reload (the OS layout direction is read at boot);
 * icons flip immediately via `isRtlNow()`. */
export function setPseudoRtlEnabled(
  on: boolean,
  storage: () => KeyValueStore = appStorage,
): void {
  if (!isDevHost()) return
  try {
    if (on) storage().setItem(PSEUDO_RTL_FLAG_KEY, JSON.stringify(true))
    else storage().removeItem(PSEUDO_RTL_FLAG_KEY)
  } catch {
    // Storage unavailable: the flag lasts for this session only.
  }
  try {
    I18nManager.allowRTL(true)
    I18nManager.forceRTL(on)
  } catch {
    // Bare test runtimes may lack the native module: the persisted flag
    // still drives `isRtlNow()` for icons.
  }
}

/** Current layout direction: the OS RTL switch, or the dev rehearsal flag.
 * Plain function (not a hook): direction changes require a reload except
 * for icon flips, so no subscription is needed. */
export function isRtlNow(
  storage: () => KeyValueStore = appStorage,
): boolean {
  try {
    if (I18nManager.isRTL) return true
  } catch {
    // Bare runtimes without the native module: fall through to the flag.
  }
  return isPseudoRtlEnabled(storage)
}

// Boot the stored locale synchronously at import: the first render already
// speaks the reader's language. Failures fall back to English, never blank.
try {
  const boot = localeStore.get()
  i18n.load(boot, CATALOGS[boot] ?? {})
  i18n.activate(boot)
} catch {
  try {
    i18n.load(DEFAULT_LOCALE, CATALOGS[DEFAULT_LOCALE] ?? {})
    i18n.activate(DEFAULT_LOCALE)
  } catch {
    // Last resort: the pre-existing empty-en behaviour.
  }
}

// Dev-only: `?locale=pseudo` on web (or the dev flag on native) renders the
// pseudo-locale on top of the stored locale. Async and best-effort: when
// the catalog was never generated, English stays.
if (isPseudoLocaleEnabled()) void activatePseudoLocale()

export function useLocale(store: LocaleStore = localeStore): LocaleCode {
  return useSyncExternalStore(store.subscribe, store.get)
}

/** Persist + activate a locale (drives `I18nProvider` re-render). */
export function setLocale(code: LocaleCode, store: LocaleStore = localeStore): void {
  store.set(code)
}

/** This BCP-47 tag is already what `Intl.*` wants (`yue-HK` included). */
export function localeTag(code: LocaleCode): string {
  return code
}

/** Locale-aware counter formatting; raw numerals on any failure. Pure. */
export function formatCount(locale: LocaleCode, n: number): string {
  try {
    return new Intl.NumberFormat(localeTag(locale)).format(n)
  } catch {
    return String(n)
  }
}

/** Locale-aware compact counter (`5.5K`); raw numerals on any failure.
 * Pure. Used where a numeral shares a card with its label and exact
 * digits would not fit — accessibility labels keep `formatCount`. */
export function formatCompactCount(locale: LocaleCode, n: number): string {
  try {
    return new Intl.NumberFormat(localeTag(locale), {
      notation: 'compact',
      maximumFractionDigits: 1,
    }).format(n)
  } catch {
    return String(n)
  }
}

/**
 * Provider-tolerant `i18n` for shared chrome (repair X9.4): inside an
 * `I18nProvider` this returns the context instance (reactive, re-renders on
 * `activate`); in a bare tree (unit tests, previews — no provider) it falls
 * back to the app singleton (same object `Root` provides, render-time
 * strings, never a throw). The call itself is unconditional, so the
 * rules-of-hooks hold; only the missing-context throw is caught.
 */
export function useI18n(): typeof i18n {
  try {
    return useLingui().i18n as unknown as typeof i18n
  } catch {
    return i18n
  }
}

export {i18n}
